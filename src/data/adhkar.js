/* =========================================
   PREPARE MORNING / EVENING TEXT
========================================= */

function adapt(
  item,
  period
) {

  return {

    ...item,

    title:
      period === 'evening'
        ? (
            item.eveningTitle ||
            item.title
          )
        : item.title,

    text:
      period === 'evening'
        ? (
            item.eveningText ||
            item.text
          )
        : (
            item.morningText ||
            item.text
          )

  }
}



